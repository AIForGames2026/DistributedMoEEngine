#!/usr/bin/env python3
"""Writes src/unicode_tables.zig (TASK-30): the Unicode data the tokenizer
needs, from Python's unicodedata. Letter, mark, number, punctuation and
symbol ranges for the pre-tokenizer patterns (the letter cases for gpt-oss's,
TASK-37), Han characters for Kimi's (TASK-39, from the regex package, since
unicodedata has no scripts), and canonical combining classes, decompositions, and
compositions for NFC.

Usage:
  python3 tools/ref/gen_unicode.py > src/unicode_tables.zig
"""
import sys
import unicodedata

import regex

MAX = 0x110000
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def canonical(cp):
    """Full canonical decomposition, or None. Hangul is handled in code."""
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<") or HANGUL_FIRST <= cp <= HANGUL_LAST:
        return None
    out = []
    for part in d.split():
        sub = int(part, 16)
        out.extend(canonical(sub) or [sub])
    return out


def main():
    cat = lambda cp: unicodedata.category(chr(cp))
    letters = ranges(lambda cp: cat(cp).startswith("L"))
    numbers = ranges(lambda cp: cat(cp).startswith("N"))
    marks = ranges(lambda cp: cat(cp).startswith("M"))
    upper = ranges(lambda cp: cat(cp) in ("Lu", "Lt"))
    lower = ranges(lambda cp: cat(cp) == "Ll")
    other_letters = ranges(lambda cp: cat(cp) in ("Lm", "Lo"))
    punctuation = ranges(lambda cp: cat(cp).startswith("P"))
    symbols = ranges(lambda cp: cat(cp).startswith("S"))
    han_re = regex.compile(r"\p{Han}")
    han = ranges(lambda cp: han_re.match(chr(cp)) is not None)

    ccc = []
    for cp in range(MAX):
        c = unicodedata.combining(chr(cp))
        if c:
            if ccc and ccc[-1][1] == cp - 1 and ccc[-1][2] == c:
                ccc[-1] = (ccc[-1][0], cp, c)
            else:
                ccc.append((cp, cp, c))

    decomp_index, decomp_data = [], []
    compose = []
    for cp in range(MAX):
        full = canonical(cp)
        if full is None:
            continue
        decomp_index.append((cp, len(decomp_data), len(full)))
        decomp_data.extend(full)
        # A primary composite: a two-part decomposition that NFC recomposes.
        parts = unicodedata.decomposition(chr(cp)).split()
        if len(parts) == 2:
            a, b = (int(p, 16) for p in parts)
            if unicodedata.normalize("NFC", chr(a) + chr(b)) == chr(cp):
                compose.append((a, b, cp))
    compose.sort()

    w = sys.stdout.write
    w(f"//! Generated by tools/ref/gen_unicode.py from Unicode {unicodedata.unidata_version}; do not edit.\n\n")
    w("// Ranges are { first, last }; combining is { first, last, class };\n")
    w("// decomp_index is { codepoint, start in decomp_data, length }; compose is { a, b, composite }.\n\n")

    def emit(name, typ, rows, fmt):
        w(f"pub const {name} = [_]{typ}{{\n")
        line = "   "
        for r in rows:
            item = " " + fmt(r) + ","
            if len(line) + len(item) > 100:
                w(line + "\n")
                line = "   "
            line += item
        w(line + "\n};\n\n")

    tup = lambda r: ".{ " + ", ".join(f"0x{x:X}" for x in r) + " }"
    emit("letters", "[2]u21", letters, tup)
    emit("numbers", "[2]u21", numbers, tup)
    emit("marks", "[2]u21", marks, tup)
    emit("upper", "[2]u21", upper, tup)
    emit("lower", "[2]u21", lower, tup)
    emit("other_letters", "[2]u21", other_letters, tup)
    emit("punctuation", "[2]u21", punctuation, tup)
    emit("symbols", "[2]u21", symbols, tup)
    emit("han", "[2]u21", han, tup)
    emit("combining", "[3]u21", ccc, tup)
    emit("decomp_index", "[3]u21", decomp_index, tup)
    emit("decomp_data", "u21", decomp_data, lambda r: f"0x{r:X}")
    emit("compose", "[3]u21", compose, tup)


if __name__ == "__main__":
    main()
